def main():
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    
    # Get all properties
    properties = cursor.execute('''
        SELECT id, city, state FROM properties
    ''').fetchall()
    
    print(f"Found {len(properties)} properties to update")
    
    updated = 0
    not_found = []
    
    for prop_id, city, state in properties:
        # Clean up city name for lookup
        city_clean = city.upper().strip()
        # Remove parenthetical suffixes like "(RAINBOW)"
        if '(' in city_clean:
            city_clean = city_clean.split('(')[0].strip()
        
        state_clean = state.upper().strip()
        key = f"{city_clean}, {state_clean}"
        
        if key in CITY_COORDS:
            lat, lon = CITY_COORDS[key]
            cursor.execute('UPDATE properties SET lat = ?, lon = ? WHERE id = ?', (lat, lon, prop_id))
            updated += 1
        else:
            not_found.append(f"{city}, {state}")
    
    conn.commit()
    conn.close()
    
    print(f"\n✅ Updated {updated} properties with city coordinates")
    
    if not_found:
        # Get unique missing cities
        unique_missing = sorted(set(not_found))
        print(f"\n⚠️  {len(unique_missing)} cities not found in database:")
        for city in unique_missing[:20]:
            print(f"    - {city}")
        if len(unique_missing) > 20:
            print(f"    ... and {len(unique_missing) - 20} more")

if __name__ == '__main__':
    main()
